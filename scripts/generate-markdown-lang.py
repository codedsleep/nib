#!/usr/bin/env python3
"""Generate data/language-specs/nib-markdown.lang: GtkSourceView's Markdown
with fenced code blocks highlighted in the language named by the fence."""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'data/language-specs/nib-markdown.lang'

# GtkSourceView language id -> info-string names (matched case-insensitively).
# Every id must be one of GtkSourceView 5's bundled languages, or the whole
# file fails to load and the editor keeps plain Markdown.
#
# Each language costs its parse time once per process, on the main thread,
# when the first note with a code fence opens: this list measured ≈ 60 ms on
# the workstation, the full bundled set ≈ 150 ms. Julia, MATLAB, R, LaTeX and
# CMake alone cost 10-20 ms each and are left out.
LANGUAGES = [
    ('rust', ['rust', 'rs']),
    ('python3', ['python', 'py', 'python3', 'py3']),
    ('js', ['javascript', 'js', 'mjs', 'cjs', 'node']),
    ('jsx', ['jsx']),
    ('typescript', ['typescript', 'ts', 'mts', 'cts']),
    ('typescript-jsx', ['tsx']),
    ('sh', ['sh', 'bash', 'shell', 'zsh', 'ksh', 'shellscript']),
    ('fish', ['fish']),
    ('json', ['json', 'jsonc', 'json5']),
    ('toml', ['toml']),
    ('yaml', ['yaml', 'yml']),
    ('ini', ['ini', 'cfg', 'conf', 'systemd']),
    ('xml', ['xml', 'svg', 'xsd', 'plist']),
    ('html', ['html', 'htm', 'xhtml']),
    ('css', ['css']),
    ('scss', ['scss', 'sass']),
    ('c', ['c', 'h']),
    ('cpp', ['cpp', 'c++', 'cc', 'cxx', 'hpp', 'hh']),
    ('c-sharp', ['csharp', 'c#', 'cs']),
    ('go', ['go', 'golang']),
    ('java', ['java']),
    ('kotlin', ['kotlin', 'kt', 'kts']),
    ('swift', ['swift']),
    ('zig', ['zig']),
    ('glsl', ['glsl', 'vert', 'frag', 'shader']),
    ('sql', ['sql', 'mysql', 'postgresql', 'postgres', 'psql', 'sqlite', 'plsql']),
    ('diff', ['diff', 'patch']),
    ('lua', ['lua']),
    ('ruby', ['ruby', 'rb']),
    ('php', ['php']),
    ('docker', ['dockerfile', 'docker', 'containerfile']),
    ('makefile', ['makefile', 'make', 'mk']),
    ('nix', ['nix']),
]

# A fence is three or more backticks or tildes, indented or not (fences sit
# inside list items). It closes on a line of the same character; a longer
# outer fence around a shorter inner one is not tracked.
FENCES = [('backticks', '`'), ('tildes', '~')]
# The name ends at the end of the line, a space, a comma or a brace, so
# `rust,ignore` and `{.rust}` work but `rusty` is not Rust.
NAME_END = r'(?=[ \t,{}]|$)'


def fence_line(char):
    return rf'^[ \t]*{char}{{3,}}'


def close_line(char):
    return escape(rf'{fence_line(char)}[ \t]*$')


HEADER = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-markdown-lang.py; edit that, not this.

     GtkSourceView's Markdown, with each fenced code block highlighted in the
     language its info string names (```rust, ~~~python, ```{.sh}). Unknown
     or missing names keep the plain code-block colour. Hidden so other
     GtkSourceView applications do not list it. -->
<language id="nib-markdown" name="Markdown (nib)" version="2.0" _section="Markup" hidden="true">
  <metadata>
    <property name="block-comment-start">&lt;!--</property>
    <property name="block-comment-end">--&gt;</property>
    <property name="suggested-suffix">.md</property>
  </metadata>
  <styles>
    <style id="code-block" name="Code Block" map-to="def:preformatted-section"/>
  </styles>
  <definitions>
'''


def escape(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def closer(kind, char):
    # A child that ends its block. The block's own <end> loses to a child
    # starting at the same place (sh backticks, Python's ~ operator); a
    # child listed first does not.
    return '\n'.join([
        f'    <context id="close-{kind}" style-ref="code-block" end-parent="true">',
        f'      <match>{close_line(char)}</match>',
        '    </context>',
    ])


def fence(context_id, kind, char, info, style, inner):
    lines = [
        f'    <context id="{context_id}-{kind}" class="no-spell-check"{style}>',
        f'      <start>{escape(fence_line(char) + info)}</start>',
        f'      <end>{close_line(char)}</end>',
        '      <include>',
        '        <context sub-pattern="0" where="start" style-ref="code-block"/>',
        '        <context sub-pattern="0" where="end" style-ref="code-block"/>',
        f'        <context ref="close-{kind}"/>',
    ]
    lines += [f'        {line}' for line in inner]
    lines += ['      </include>', '    </context>']
    return '\n'.join(lines)


def generate():
    blocks = [closer(kind, char) for kind, char in FENCES]
    refs = []
    for kind, char in FENCES:
        for lang, names in LANGUAGES:
            alternatives = '|'.join(re.escape(n).replace('\\-', '-') for n in names)
            info = rf'[ \t]*\{{?\.?(?i:{alternatives}){NAME_END}.*$'
            inner = [f'<context ref="{lang}:{lang}"/>']
            blocks.append(fence(f'fenced-{lang}', kind, char, info, '', inner))
            refs.append(f'fenced-{lang}-{kind}')
    # Unknown or missing names: one colour, as GtkSourceView's Markdown does.
    for kind, char in FENCES:
        blocks.append(fence('fenced-code', kind, char, '.*$', ' style-ref="code-block"', []))
        refs.append(f'fenced-code-{kind}')
    top = '\n'.join([
        '    <context id="nib-markdown">',
        '      <include>',
        *[f'        <context ref="{ref}"/>' for ref in refs],
        '        <context ref="markdown:markdown"/>',
        '      </include>',
        '    </context>',
    ])
    return HEADER + '\n\n'.join(blocks) + '\n\n' + top + '\n  </definitions>\n</language>\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the committed file is stale')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            raise SystemExit(f'{OUT.relative_to(ROOT)} is stale; run scripts/generate-markdown-lang.py')
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)


if __name__ == '__main__':
    main()
